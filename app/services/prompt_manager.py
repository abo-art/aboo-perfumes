def build_recommendations_prompt(
    perfume: Perfume,
    answers: List[UserAnswer],
    catalog_context: List[Perfume]
) -> str:
    """Prompt for generating the final ranked TOP-10 real perfumes with justification."""
    answers_text = "\n".join([
        f"- Вопрос {a.question_id}: {a.question or 'Вопрос по предпочтениям'} -> Ответ: {a.answer}"
        for a in answers
    ])

    # Provide candidate real perfumes from database as ground truth reference
    catalog_sample = "\n".join([
        f"• {p.brand} — {p.name} (Семейство: {p.family}; Ключевые ноты: {', '.join(p.all_notes[:5])}; Характер: {p.character})"
        for p in catalog_context[:45]
    ])

    return f"""Контекст подбора:
1. Прошлый любимый аромат пользователя:
   {perfume.brand} — {perfume.name}
   Семейство: {perfume.family}
   Ключевые ноты: {', '.join(perfume.all_notes[:7])}
   Характер: {perfume.character}

2. Ответы пользователя на уточняющие вопросы сомелье:
{answers_text}

3. База реальных эталонных ароматов на выбор (используй ТОЛЬКО реально существующие ароматы из этого пула или проверенной мировой парфюмерии):
{catalog_sample}

СТРОГИЕ ПРАВИЛА:
1. Выдай РОВНО 10 реальных ароматов. Никаких выдуманных брендов и названий!
2. Ранжируй список от 1 до 10:
   - 1-3: Точные попадания в ДНК любимого парфюма с учетом ответов.
   - 4-7: Элегантные вариации и развитие темы.
   - 8-10: Смелые, неизбитые альтернативы для расширения ольфакторного горизонта.
3. Для каждого аромата обязательно укажи бренд, название, семейство, ноты и экспертное обоснование («Почему он тебе зайдет»).

Формат ответа — СТРОГО чистый JSON:
{{
  "status": "success",
  "recommendations": [
    {{
      "rank": 1,
      "brand": "Бренд",
      "name": "Название парфюма",
      "family": "Семейство",
      "notes": ["нота 1", "нота 2", "нота 3"],
      "image_url": "https://example.com/images/perfume.jpg",
      "reason": "Обоснование, почему это подходит пользователю с учетом ответов"
    }}
  ]
}}"""
